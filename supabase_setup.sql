-- 1. Create Patients Table (with 4-tier triage status: 'green', 'amber', 'blue', 'red')
CREATE TABLE IF NOT EXISTS public.patients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    age INTEGER NOT NULL,
    dept TEXT NOT NULL,
    dx TEXT NOT NULL,
    phone TEXT NOT NULL,
    day_post_discharge INTEGER DEFAULT 1,
    status TEXT DEFAULT 'green', -- 'green' (Stable), 'amber' (Under Observation), 'blue' (Follow-Up Due), 'red' (Needs Care)
    is_flagged BOOLEAN DEFAULT FALSE,
    medications TEXT DEFAULT '',
    medical_history TEXT DEFAULT '',
    risk_factors TEXT DEFAULT '',
    ai_suggestions JSONB DEFAULT '[]'::jsonb,
    is_demo BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Ensure columns exist if table was already created earlier
ALTER TABLE public.patients ADD COLUMN IF NOT EXISTS status TEXT DEFAULT 'green';
ALTER TABLE public.patients ADD COLUMN IF NOT EXISTS is_flagged BOOLEAN DEFAULT FALSE;

-- 2. Create Follow-Up Questions & Patient Answers Table
CREATE TABLE IF NOT EXISTS public.follow_up_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT REFERENCES public.patients(id) ON DELETE CASCADE,
    question_text TEXT NOT NULL,
    reply_text TEXT,
    severity TEXT DEFAULT 'normal', -- 'normal', 'moderate', 'severe'
    day_number INTEGER DEFAULT 1,
    is_today BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Create WhatsApp & Patient Recovery Chat Messages Table
CREATE TABLE IF NOT EXISTS public.chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT REFERENCES public.patients(id) ON DELETE CASCADE,
    sender TEXT NOT NULL, -- 'hospital', 'patient', 'ai', 'system'
    text TEXT NOT NULL,
    is_concerning BOOLEAN DEFAULT FALSE,
    concern_reason TEXT,
    is_demo BOOLEAN DEFAULT FALSE,
    status TEXT DEFAULT 'delivered', -- 'sent', 'delivered', 'read'
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Ensure chat columns exist if table was already created
ALTER TABLE public.chat_messages ADD COLUMN IF NOT EXISTS is_concerning BOOLEAN DEFAULT FALSE;
ALTER TABLE public.chat_messages ADD COLUMN IF NOT EXISTS concern_reason TEXT;
ALTER TABLE public.chat_messages ADD COLUMN IF NOT EXISTS is_demo BOOLEAN DEFAULT FALSE;
ALTER TABLE public.chat_messages ADD COLUMN IF NOT EXISTS status TEXT DEFAULT 'delivered';

-- 4. Enable Row Level Security (RLS)
ALTER TABLE public.patients ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.follow_up_questions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.chat_messages ENABLE ROW LEVEL SECURITY;

-- 5. RLS Policies: Permit full access for authenticated hospital staff & anon demo mode
DROP POLICY IF EXISTS "Allow demo and authenticated full access on patients" ON public.patients;
CREATE POLICY "Allow demo and authenticated full access on patients"
    ON public.patients FOR ALL
    USING (true)
    WITH CHECK (true);

DROP POLICY IF EXISTS "Allow demo and authenticated full access on questions" ON public.follow_up_questions;
CREATE POLICY "Allow demo and authenticated full access on questions"
    ON public.follow_up_questions FOR ALL
    USING (true)
    WITH CHECK (true);

DROP POLICY IF EXISTS "Allow demo and authenticated full access on chat" ON public.chat_messages;
CREATE POLICY "Allow demo and authenticated full access on chat"
    ON public.chat_messages FOR ALL
    USING (true)
    WITH CHECK (true);

-- Enable Realtime publication for chat_messages table (safely)
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_publication WHERE pubname = 'supabase_realtime') THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.chat_messages;
  END IF;
EXCEPTION
  WHEN duplicate_object THEN NULL;
  WHEN undefined_table THEN NULL;
END $$;

